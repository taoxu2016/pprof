# Compare two trees of pprofR fixtures (LOGISTIC_L1_PLAN §3): the diff report a regeneration needs
# (CLAUDE.md) and the determinism check, where two runs from one commit must agree byte for byte.
#
# Usage, from the repository root:
#   Rscript dev/reference/pprofr/compare.R <old dir> <new dir> [--report FILE] [--strict]
# For each fixture: whether it is in both trees and whether the files are byte for byte equal; where they
# are not, each record whose value, error, warnings, or messages differ, with the largest absolute and
# relative differences of its numbers. The manifests are compared without the fields that name the run
# (`created`, the generator's commit, and whether its inputs were dirty). With --strict the exit status
# is 1 when anything differs.

args <- commandArgs(trailingOnly = TRUE)
strict <- "--strict" %in% args
args <- setdiff(args, "--strict")
report_file <- NULL
if ("--report" %in% args) {
  k <- match("--report", args)
  report_file <- args[[k + 1L]]
  args <- args[-c(k, k + 1L)]
}
if (length(args) != 2L) stop("Usage: compare.R <old dir> <new dir> [--report FILE] [--strict]", call. = FALSE)
old_dir <- args[[1]]
new_dir <- args[[2]]

# The numbers of an object, flattened in a fixed order (names and attributes left aside).
numbers <- function(x) {
  if (is.null(x)) return(numeric())
  if (is.factor(x)) return(as.numeric(as.character(x)))
  if (is.numeric(x) || is.logical(x)) return(as.numeric(x))
  if (is.list(x)) return(unlist(lapply(x, numbers), use.names = FALSE))
  numeric()
}
largest_difference <- function(a, b) {
  a <- numbers(a)
  b <- numbers(b)
  if (length(a) != length(b)) return(c(abs = NA, rel = NA))
  both <- is.finite(a) & is.finite(b)
  if (!any(both)) return(c(abs = 0, rel = 0))
  d <- abs(a[both] - b[both])
  c(abs = max(d), rel = max(d / pmax(abs(b[both]), .Machine$double.xmin)))
}

files <- sort(union(list.files(old_dir, pattern = "\\.rds$"), list.files(new_dir, pattern = "\\.rds$")))
rows <- character()
details <- character()
n_differ <- 0L
for (f in files) {
  in_old <- file.exists(file.path(old_dir, f))
  in_new <- file.exists(file.path(new_dir, f))
  if (!(in_old && in_new)) {
    rows <- c(rows, sprintf("| %s | %s | | |", f, if (in_old) "only in the old tree" else "only in the new tree"))
    n_differ <- n_differ + 1L
    next
  }
  if (identical(unname(tools::md5sum(file.path(old_dir, f))), unname(tools::md5sum(file.path(new_dir, f))))) {
    rows <- c(rows, sprintf("| %s | byte for byte equal | | |", f))
    next
  }
  n_differ <- n_differ + 1L
  old <- readRDS(file.path(old_dir, f))
  new <- readRDS(file.path(new_dir, f))
  names_all <- union(names(old$records), names(new$records))
  changed <- character()
  for (r in names_all) {
    a <- old$records[[r]]
    b <- new$records[[r]]
    if (is.null(a) || is.null(b)) {
      changed <- c(changed, sprintf("  - `%s`: only in the %s tree", r, if (is.null(a)) "new" else "old"))
    } else if (!identical(a, b)) {
      what <- c(if (!identical(a$value, b$value)) "value", if (!identical(a$error, b$error)) "error",
                if (!identical(a$warnings, b$warnings)) "warnings", if (!identical(a$messages, b$messages)) "messages",
                if (!identical(a$call, b$call)) "call")
      d <- largest_difference(a$value, b$value)
      changed <- c(changed, sprintf("  - `%s`: %s differ; largest difference %.3g absolute, %.3g relative", r,
                                    paste(what, collapse = ", "), d[["abs"]], d[["rel"]]))
    }
  }
  data_same <- identical(old$data, new$data)
  rows <- c(rows, sprintf("| %s | differs | %d of %d | %s |", f, length(changed), length(names_all),
                          if (data_same) "equal" else "differ"))
  details <- c(details, sprintf("- `%s`:", f), changed)
}

strip <- function(m) {
  m$created <- NULL
  m$generator$git_commit <- NULL
  m$generator$dirty <- NULL
  for (k in seq_along(m$cases)) m$cases[[k]]$md5 <- NULL
  m
}
manifest_old <- file.path(old_dir, "manifest.json")
manifest_new <- file.path(new_dir, "manifest.json")
manifest_line <- if (file.exists(manifest_old) && file.exists(manifest_new)) {
  same <- identical(strip(jsonlite::read_json(manifest_old)), strip(jsonlite::read_json(manifest_new)))
  if (!same) n_differ <- n_differ + 1L
  sprintf("The manifests, without the fields that name the run and the files' checksums: %s.",
          if (same) "equal" else "they differ")
} else {
  n_differ <- n_differ + 1L
  "A manifest is missing."
}

lines <- c("# pprofR fixtures: comparison", "",
           sprintf("Old tree: `%s`. New tree: `%s`. Generated by `dev/reference/pprofr/compare.R` on %s.", old_dir,
                   new_dir, format(Sys.time(), tz = "UTC", usetz = TRUE)), "",
           sprintf("%d of %d fixtures differ. %s", sum(!grepl("byte for byte equal", rows)), length(files),
                   manifest_line),
           "", "| Fixture | Files | Records that differ | Data |", "|---|---|---|---|", rows,
           if (length(details)) c("", "## Records that differ", "", details))
if (is.null(report_file)) writeLines(lines) else writeLines(lines, report_file)
cat(sprintf("compared %d fixtures: %d differences\n", length(files), n_differ))
if (strict && n_differ > 0L) quit(status = 1L)
